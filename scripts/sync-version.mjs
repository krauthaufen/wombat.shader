// Writes packages/shader/src/version.ts from packages/shader/package.json, so
// the compiler can report its version at runtime (consumers key caches of
// compiled output on it, e.g. wombat.rendering's heap-shader cache).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "packages/shader/package.json"), "utf8"));
const file = path.join(root, "packages/shader/src/version.ts");
const text = `// Generated by scripts/sync-version.mjs from package.json — do not edit.\n/** The \`@aardworx/wombat.shader\` package version. */\nexport const VERSION = "${pkg.version}";\n`;
if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) fs.writeFileSync(file, text);
